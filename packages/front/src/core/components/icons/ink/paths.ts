function star(cx: number, cy: number, rOut: number, rIn: number): Pt[] {
  const pts: Pt[] = [];

  for (let i = 0; i < 10; i++) {
    const a = ((-90 + i * 36) * Math.PI) / 180;
    const r = i % 2 ? rIn : rOut;
    pts.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
  }

  return pts;
}

