// Ink icon path data: the single source for the Vue icon set (index.ts) and
// the static review gallery (scripts/build-ink-gallery.mjs).
//
// Every glyph is drawn on a 24 grid with ~2px padding, stroke only, by the
// same small set of "hand" primitives below: lines bow slightly, circles are
// two overlapping arcs that stop just short of closing, corners overshoot.
// Wobble is deterministic so output is stable across builds.
//
// Keep this file free of runtime-only TS syntax (enums, namespaces) so Node
// can import it directly with type stripping.

type Pt = readonly [number, number];

const f = (n: number): number => Math.round(n * 100) / 100;
const pt = (p: Pt): string => `${f(p[0])} ${f(p[1])}`;

/** Quadratic segment from a to b, bowed perpendicular by `bend` units. */
function bow(a: Pt, b: Pt, bend: number): string {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const len = Math.hypot(dx, dy) || 1;
  const c: Pt = [
    (a[0] + b[0]) / 2 - (dy / len) * bend,
    (a[1] + b[1]) / 2 + (dx / len) * bend,
  ];

  return `Q${pt(c)} ${pt(b)}`;
}

/** A single stroke with a subtle curve. */
function line(a: Pt, b: Pt, bend = 0.3): string {
  return `M${pt(a)} ${bow(a, b, bend)}`;
}

/** Connected strokes with sharp (round-joined) corners; bends alternate. */
function poly(points: Pt[], bend = 0.25, close = false): string {
  const pts = close ? [...points, points[0]] : points;
  let d = `M${pt(pts[0])}`;

  for (let i = 1; i < pts.length; i++) {
    d += ` ${bow(pts[i - 1], pts[i], i % 2 ? bend : -bend * 0.7)}`;
  }

  if (close) {
    // the brush runs a hair past where it started
    const a = points[0];
    const b = points[1];
    const len = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
    const k = Math.min(0.9, len * 0.3) / len;
    d += ` L${pt([a[0] + (b[0] - a[0]) * k, a[1] + (b[1] - a[1]) * k])}`;
  }

  return d;
}

/** Smooth freehand stroke through points (Catmull-Rom as cubic Béziers). */
function smooth(points: Pt[]): string {
  const p = points;
  let d = `M${pt(p[0])}`;

  for (let i = 0; i < p.length - 1; i++) {
    const p0 = p[i - 1] ?? p[i];
    const p1 = p[i];
    const p2 = p[i + 1];
    const p3 = p[i + 2] ?? p2;
    const c1: Pt = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2: Pt = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += ` C${pt(c1)} ${pt(c2)} ${pt(p2)}`;
  }

  return d;
}

/**
 * Hand arc. Angles in degrees, 0 = 3 o'clock, positive = clockwise (SVG y-down).
 * a1 may be smaller than a0 to draw counter-clockwise.
 */
function arc(
  cx: number,
  cy: number,
  r: number,
  a0: number,
  a1: number,
  wob = 0.03,
  phase = 0,
  ry = r,
): string {
  const span = a1 - a0;
  const steps = Math.max(2, Math.ceil(Math.abs(span) / 28));
  const pts: Pt[] = [];

  for (let i = 0; i <= steps; i++) {
    const a = ((a0 + (span * i) / steps) * Math.PI) / 180;
    const k = 1 + wob * Math.sin(2.3 * a + phase);
    pts.push([cx + Math.cos(a) * r * k, cy + Math.sin(a) * ry * k]);
  }

  return smooth(pts);
}

/** Circle as two overlapping arcs that stop just short of closing. */
function ring(
  cx: number,
  cy: number,
  r: number,
  start = -110,
  wob = 0.03,
): string {
  const w = r < 3 ? wob * 0.5 : wob;

  return `${arc(cx, cy, r, start, start + 200, w, 0.4)} ${arc(cx, cy, r * 1.025, start + 186, start + 352, w, 1.7)}`;
}

/** Ellipse variant of ring. */
function oval(
  cx: number,
  cy: number,
  rx: number,
  ry: number,
  start = -100,
): string {
  return `${arc(cx, cy, rx, start, start + 200, 0.025, 0.9, ry)} ${arc(cx, cy, rx * 1.03, start + 186, start + 352, 0.025, 2.2, ry * 1.01)}`;
}

/** Rounded rectangle, edges slightly bowed, end overlapping the start. */
function rect(x: number, y: number, w: number, h: number, r = 2): string {
  const x2 = x + w;
  const y2 = y + h;
  const b = 0.18;

  return [
    `M${pt([x + r + 0.6, y + 0.05])}`,
    bow([x + r + 0.6, y + 0.05], [x2 - r, y], b),
    `Q${pt([x2, y])} ${pt([x2, y + r])}`,
    bow([x2, y + r], [x2 + 0.05, y2 - r], b),
    `Q${pt([x2, y2])} ${pt([x2 - r, y2])}`,
    bow([x2 - r, y2], [x + r, y2 - 0.05], b),
    `Q${pt([x, y2])} ${pt([x, y2 - r])}`,
    bow([x, y2 - r], [x - 0.05, y + r], b),
    `Q${pt([x, y])} ${pt([x + r, y])}`,
    `L${pt([x + r + 1.2, y + 0.05])}`,
  ].join(' ');
}

/** A tiny ink dot (round cap of a zero-length stroke). */
function dot(x: number, y: number): string {
  return `M${pt([x, y])}h.01`;
}

/** A slightly heavier ink blot. */
function blot(x: number, y: number, r = 0.55): string {
  return `M${pt([x - r, y])}a${r} ${r} 0 1 0 ${f(r * 2)} 0a${r} ${r} 0 1 0 ${f(-r * 2)} 0`;
}

function rotate(points: Pt[], deg: number, cx = 12, cy = 12): Pt[] {
  const a = (deg * Math.PI) / 180;
  const c = Math.cos(a);
  const s = Math.sin(a);

  return points.map(
    ([x, y]) =>
      [
        cx + (x - cx) * c - (y - cy) * s,
        cy + (x - cx) * s + (y - cy) * c,
      ] as Pt,
  );
}

function mirror(points: Pt[], axis = 12): Pt[] {
  return points.map(([x, y]) => [axis * 2 - x, y] as Pt);
}

function bloom(
  cx: number,
  cy: number,
  rIn: number,
  rOut: number,
  lobes: number,
): string {
  const pts: Pt[] = [];

  for (let deg = -90; deg <= 262; deg += 11) {
    const a = (deg * Math.PI) / 180;
    const r =
      rIn + (rOut - rIn) * Math.abs(Math.cos((lobes / 2) * (a + Math.PI / 2)));
    pts.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
  }

  return smooth(pts);
}

